import pathlib
import argparse

def writeFromFileSrc(file, varName, genFilePath):
    with open(genFilePath, "a") as genFile:
        shader = file.read()
        genFile.write(f"namespace ShaderSet {{const char* Get{varName}(){{return R\"({shader})\";}}}}")

def writeFromFileH(varName, genFilePath):
    with open(genFilePath, "a") as genFile:
        genFile.write(f"namespace ShaderSet {{const char* Get{varName}();}}")

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("-f", "--folder", help = "the folder where to put the generated dir")
    parser.add_argument("-w", "--working_folder", help = "the folder where to pick the shaders")

    outDir = parser.parse_args().folder
    shadersFolder = pathlib.Path(parser.parse_args().working_folder)

    genDir = pathlib.Path(outDir) / "generated"
    genDir.mkdir(parents = True, exist_ok = True)

    print(genDir)

    with open(genDir / "shaders.h", "w") as shadersHeader:
        shadersHeader.write("// Generated by generate_header_shader.py\n #pragma once\n")

    with open(genDir / "shaders.cpp", "w") as shadersSrc:
        shadersSrc.write("// Generated by generate_header_shader.py\n #include \"shaders.h\"\n")

    with open(shadersFolder / "Quad.frag", "r") as quadFragFile:
        writeFromFileSrc(quadFragFile, "quadFrag", genDir / "shaders.cpp")
        writeFromFileH("quadFrag", genDir / "shaders.h")

    with open(shadersFolder / "Quad.vert", "r") as quadVertFile:
        writeFromFileSrc(quadVertFile, "quadVert", genDir / "shaders.cpp")
        writeFromFileH("quadVert", genDir / "shaders.h")

    with open(shadersFolder / "Screen.frag", "r") as quadFragFile:
        writeFromFileSrc(quadFragFile, "ScreenFrag", genDir / "shaders.cpp")
        writeFromFileH("ScreenFrag", genDir / "shaders.h")

    with open(shadersFolder / "Screen.vert", "r") as quadVertFile:
        writeFromFileSrc(quadVertFile, "ScreenVert", genDir / "shaders.cpp")
        writeFromFileH("ScreenVert", genDir / "shaders.h")

    with open(shadersFolder / "Text.frag", "r") as quadFragFile:
        writeFromFileSrc(quadFragFile, "TextFrag", genDir / "shaders.cpp")
        writeFromFileH("TextFrag", genDir / "shaders.h")

    with open(shadersFolder / "Text.vert", "r") as quadVertFile:
        writeFromFileSrc(quadVertFile, "TextVert", genDir / "shaders.cpp")
        writeFromFileH("TextVert", genDir / "shaders.h")

    with open(shadersFolder / "HUD.frag", "r") as quadFragFile:
        writeFromFileSrc(quadFragFile, "HUDFrag", genDir / "shaders.cpp")
        writeFromFileH("HUDFrag", genDir / "shaders.h")

    with open(shadersFolder / "HUD.vert", "r") as quadVertFile:
        writeFromFileSrc(quadVertFile, "HUDVert", genDir / "shaders.cpp")
        writeFromFileH("HUDVert", genDir / "shaders.h")

    with open(genDir / "shaders.h", "a") as shadersHeader:
        shadersHeader.write("\n")



if __name__ == "__main__":
    main()
