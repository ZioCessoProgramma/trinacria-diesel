import pathlib
import argparse

def writeFromFileSrc(file, varName, genFilePath):
    with open(genFilePath, "a") as genFile:
        shader = file.read()
        genFile.write(f"namespace ShaderSet {{const char* {varName} = R\"({shader})\";}}")

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--folder", help = "the folder where to put the generated dir")
    parser.add_argument("--working_folder", help = "the folder where to pick the shaders")

    outDir = parser.parse_args().folder
    shadersFolder = pathlib.Path(parser.parse_args().working_folder)

    genDir = pathlib.Path(outDir) / "generated"
    genDir.mkdir(parents = True, exist_ok = True)

    with open(genDir / "shaders.h", "w") as shadersHeader:
        shadersHeader.write("// Generated by generate_header_shader.py\n #pragma once\n namespace ShaderSet {}")

    with open(genDir / "shaders.cpp", "w") as shadersSrc:
        shadersSrc.write("// Generated by generate_header_shader.py\n #include \"shaders.h\"\n")

    with open(shadersFolder / "Quad.frag", "r") as quadFragFile:
        writeFromFileSrc(quadFragFile, "quadFrag", genDir / "shaders.cpp")

    with open(shadersFolder / "Quad.vert", "r") as quadVertFile:
        writeFromFileSrc(quadVertFile, "quadVert", genDir / "shaders.cpp")

if __name__ == "__main__":
    main()
