import pathlib
import argparse



def writeFromFile(file, varName, genFilePath):
    with open(genFilePath, "a") as genFile:
        shader = file.read()
        genFile.write(f"// Generated by python\n const char* {varName} = \"{shader}\";")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("folder", help = "the folder where to put the generated dir")

    outDir = parser.parse_args().folder

    genDir = pathlib.Path(outDir) / "generated"
    genDir.mkdir(parents = True, exist_ok = True)

    open(genDir / "shaders.h", "w").close()

    with open("Test1/assets/shaders/Quad.frag", "r") as quadFragFile:
        writeFromFile(quadFragFile, "quadFrag", genDir / "shaders.h")

    with open("Test1/assets/shaders/Quad.vert", "r") as quadVertFile:
        writeFromFile(quadVertFile, "quadVert", genDir / "shaders.h")

if __name__ == "__main__":
    main()
